import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildPairMatrix, parseFormatRegistry } from './format-pairs.mjs';

/**
 * Generates the directional conversion landing pages README §24 requires.
 *
 * "Every tool × every relevant format pair … as distinct pages even though they
 * share one engine op". The site shipped one bidirectional page per format
 * (`/word-pdf`), so a search for "PDF to Word" and "Word to PDF" both landed on
 * the same URL, and the from-PDF half of the matrix had almost no pages at all:
 * of 35 conversion routes, only two passed `direction="from-pdf"`.
 *
 * Each generated page is a prop-pass to `ConversionTool`, the same shell the
 * hand-written routes use, so it inherits the catalogue, JSON-LD, canonical,
 * hreflang and the real conversion path rather than re-implementing any of it.
 *
 * Only *supported* formats generate pages. An unavailable format gets no landing
 * page: the registry supplies a typed `unavailableReason` that a route can
 * render honestly, and a prerendered page for an operation that cannot run is a
 * doorway page — thin content that reads as a promise the product does not keep.
 *
 * Existing routes are never overwritten. `/pdf-to-markdown` is hand-written and
 * richer than anything generated, so the generator leaves it alone.
 */

const page = ({ title, format, label, direction }) => `<script lang="ts">
  import ConversionTool from '$lib/ConversionTool.svelte';
</script>

<!--
  Generated by scripts/generate-conversion-routes.mjs — do not hand-edit.

  One directional page per format × direction (README §24). The engine operation
  is shared with the opposite direction; only the entry point differs, which is
  why these are distinct pages rather than tabs on one.
-->
<ConversionTool
  title="${title}"
  description="${descriptionFor(direction, label)}"
  format="${format}"
  direction="${direction}"
  accept="${acceptFor(format)}"
/>
`;

/** Copy written per direction, so each page answers its own search intent. */
function descriptionFor(direction, label) {
  return direction === 'to-pdf'
    ? `Convert ${label} files to PDF locally, in your browser. Nothing is uploaded.`
    : `Turn PDF pages into ${label} locally, in your browser. Nothing is uploaded.`;
}

/**
 * The `accept` attribute for a format.
 *
 * Taken from the registry's own MIME types rather than guessed, so a generated
 * page's file picker accepts exactly what the engine accepts. Rejects are
 * approximate but documented; an over-broad accept is a UX annoyance, not a
 * correctness bug, because the engine types the failure.
 */
function acceptFor(format) {
  const MIME = {
    docx: '.docx,application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    xlsx: '.xlsx,application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    pptx: '.pptx,application/vnd.openxmlformats-officedocument.presentationml.presentation',
    odt: '.odt,application/vnd.oasis.opendocument.text',
    ods: '.ods,application/vnd.oasis.opendocument.spreadsheet',
    odp: '.odp,application/vnd.oasis.opendocument.presentation',
    epub: '.epub,application/epub+zip',
    csv: '.csv,text/csv',
    html: '.html,.htm,text/html',
    md: '.md,.markdown,text/markdown',
    txt: '.txt,text/plain',
    rtf: '.rtf,application/rtf',
    zip: '.zip,application/zip',
    png: '.png,image/png',
    jpg: '.jpg,.jpeg,image/jpeg',
  };
  return MIME[format] ?? '.pdf,application/pdf';
}

async function main() {
  const root = process.cwd();
  const routesRoot = resolve(root, 'apps/web/src/routes');
  const registry = parseFormatRegistry(
    await readFile(resolve(root, 'packages/engine/src/conversion/registry.ts'), 'utf8'),
  );
  const matrix = buildPairMatrix(registry);

  const check = process.argv.includes('--check');
  const written = [];
  const skipped = [];

  for (const pair of matrix) {
    const directory = join(routesRoot, pair.slug);
    const target = join(directory, '+page.svelte');
    if (existsSync(target)) {
      // Never clobber a hand-written route: `/pdf-to-markdown` predates the
      // generator and carries a richer description than a template would.
      skipped.push(pair.slug);
      continue;
    }
    if (check) {
      written.push(pair.slug);
      continue;
    }
    await mkdir(directory, { recursive: true });
    await writeFile(target, page(pair));
    written.push(pair.slug);
  }

  if (check) {
    if (written.length > 0) {
      console.error(
        `${written.length} conversion route(s) are missing: ${written.join(', ')}\n` +
          'run `pnpm generate:conversions` to create them.',
      );
      process.exitCode = 1;
    } else {
      console.log(`conversion routes are current (${matrix.length} pairs)`);
    }
    return;
  }
  console.log(
    `generated ${written.length} directional conversion routes ` +
      `(${skipped.length} left as hand-written: ${skipped.join(', ') || 'none'})`,
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
