async function main() {
  const root = process.cwd();
  const { manifest, pairs } = await loadDirectoryInputs(root);
  const directory = buildDirectory(manifest, pairs);

  if (directory.ungrouped.length > 0) {
    // An ungrouped route is a route nobody can find, which defeats the point
    // of the directory. Failing here makes a new route force a decision about
    // where it belongs.
    console.error(
      `these routes are in no directory group: ${directory.ungrouped
        .map((item) => item.slug)
        .join(', ')}\n` +
        'add each to a GROUPS match or to BIDIRECTIONAL_SLUGS in scripts/tool-directory.mjs',
    );
    process.exitCode = 1;
    return;
  }

  const target = resolve(root, 'apps/web/src/lib/ToolDirectory.svelte');
  await writeFile(target, render(directory));
  console.log(
    `wrote ToolDirectory.svelte — ${directory.groups.reduce(
      (sum, group) => sum + group.items.length,
      0,
    )} routes in ${directory.groups.length} groups`,
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
