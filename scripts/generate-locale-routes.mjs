import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { findLocalizableRoutes } from './localizable-routes.mjs';

/**
 * Generates the `[locale]` route tree.
 *
 * Only `/invoice-creator` and `/e-invoice` have a localized variant today, so
 * 58 tool routes ship English-only even though their shell reads a locale from
 * context. Each generated page renders the *canonical* route component
 * unchanged:
 *
 *     import Route from '../../crop-pdf/+page.svelte';
 *     <Route />
 *
 * The locale arrives through the `[locale]` layout's context, which the four
 * shells read. That is what keeps a route defined once and rendered in three
 * locales — a generated page that re-declared `title`, `format`, `options` and
 * the rest would be a second place to update whenever a tool changed, and
 * would drift silently.
 */
const LOCALES = ['en', 'en-XA', 'ar'];

const ENTRIES_PAGE = `/** Prerenders the page for every supported locale (README §21). */
export const entries = () => [${LOCALES.map((locale) => `{ locale: '${locale}' }`).join(', ')}];
`;

function buildPage(slug) {
  return `<script lang="ts">
  import Route from '../../${slug}/+page.svelte';
</script>

<!--
  Generated by scripts/generate-locale-routes.mjs — do not hand-edit.

  Renders the canonical route unchanged. The locale comes from the [locale]
  layout's context, which the page shells read, so a route is defined once and
  localized without a second copy of its props drifting out of date.
-->
<Route />
`;
}

/**
 * Whether a generated file on disk still matches what would be written.
 *
 * Compared on content rather than on raw bytes: git checks text files out with
 * CRLF on Windows (`core.autocrlf=true`, and this repository has no
 * `.gitattributes`), while the templates below are LF. A byte comparison
 * therefore reported correctly committed generated routes as stale on any CRLF
 * checkout. Same guard as `generate-route-manifest.mjs` and
 * `verify-licenses.mjs`.
 */
export function isCurrent(existing, generated) {
  if (existing === undefined) return false;
  return existing.replace(/\r\n/gu, '\n') === generated;
}

async function main() {
  const root = process.cwd();
  const routesRoot = resolve(root, 'apps/web/src/routes');
  const routes = await findLocalizableRoutes(routesRoot);
  const check = process.argv.includes('--check');
  const stale = [];

  for (const { route } of routes) {
    const slug = route.replace(/^\//u, '');
    const dir = join(routesRoot, '[locale]', slug);
    const pagePath = join(dir, '+page.svelte');
    const body = buildPage(slug);

    const [existingPage, existingEntries] = await Promise.all([
      readFile(pagePath, 'utf8').catch(() => undefined),
      readFile(join(dir, '+page.ts'), 'utf8').catch(() => undefined),
    ]);
    if (isCurrent(existingPage, body) && isCurrent(existingEntries, ENTRIES_PAGE)) continue;
    if (check) {
      stale.push(route);
      continue;
    }
    await mkdir(dir, { recursive: true });
    await writeFile(pagePath, body);
    await writeFile(join(dir, '+page.ts'), ENTRIES_PAGE);
  }

  if (check) {
    if (stale.length > 0) {
      console.error(
        `localized routes are stale for ${stale.length} route(s): ${stale.join(', ')}\n` +
          'run `pnpm generate:locales` to update them.',
      );
      process.exitCode = 1;
    } else {
      console.log(`localized routes are current (${routes.length} routes)`);
    }
    return;
  }
  console.log(`localized ${routes.length} routes under [locale]`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
